"""Command-line interface for the Stylistic Text Generator Comparator."""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from app.core import (
    NGramModel,
    format_side_by_side,
)
from app.llm import (
    generate_llm,
    get_trainable_parameters,
    inject_lora_adapters,
    load_lora_weights,
    load_model_and_tokenizer,
    save_lora_weights,
    train_lora,
)
from app.storage import load_corpus


def build_parser() -> argparse.ArgumentParser:
    """Construct command-line argument parser."""
    parser = argparse.ArgumentParser(
        prog="stylistic-text-generator-comparator",
        description="Sports journalists' comparator tool: compare text generated by an N-gram model vs a LoRA-adapted LLM.",
    )
    sub = parser.add_subparsers(dest="command", help="Available subcommands")

    # Command: hello (preserves compatibility with test_smoke.py)
    sub.add_parser("hello", help="Check that everything is wired up and ready")

    # Command: compare (Milestone 6 primary CLI tool)
    compare_p = sub.add_parser(
        "compare",
        help="Compare text generation side-by-side between N-gram and LoRA-adapted LLM",
    )
    compare_p.add_argument(
        "--prompt",
        "-p",
        type=str,
        default="Here comes Manchester on the counter-attack",
        help="Starting prompt for commentary generation",
    )
    compare_p.add_argument(
        "--corpus",
        "-c",
        type=str,
        default=None,
        help="Path to sports commentary plain text corpus file",
    )
    compare_p.add_argument(
        "--ngram-order",
        "-n",
        type=int,
        default=3,
        help="Order N for the N-gram language model (default: 3)",
    )
    compare_p.add_argument(
        "--max-tokens",
        "-m",
        type=int,
        default=35,
        help="Maximum tokens to generate (default: 35)",
    )
    compare_p.add_argument(
        "--epochs",
        "-e",
        type=int,
        default=2,
        help="Number of LoRA fine-tuning epochs (default: 2)",
    )
    compare_p.add_argument(
        "--rank",
        "-r",
        type=int,
        default=4,
        help="LoRA rank parameter (default: 4)",
    )
    compare_p.add_argument(
        "--alpha",
        type=float,
        default=16.0,
        help="LoRA alpha scaling parameter (default: 16.0)",
    )
    compare_p.add_argument(
        "--model",
        type=str,
        default="distilgpt2",
        help="Hugging Face pre-trained model name (default: distilgpt2)",
    )
    compare_p.add_argument(
        "--save-lora",
        type=str,
        default=None,
        help="Path to save trained LoRA adapter weights",
    )
    compare_p.add_argument(
        "--load-lora",
        type=str,
        default=None,
        help="Path to load existing LoRA adapter weights without retraining",
    )

    # Command: train-lora
    train_p = sub.add_parser("train-lora", help="Fine-tune and save LoRA adapter weights")
    train_p.add_argument("--corpus", "-c", type=str, default=None, help="Corpus path")
    train_p.add_argument("--epochs", "-e", type=int, default=3, help="Training epochs")
    train_p.add_argument("--rank", "-r", type=int, default=4, help="LoRA rank")
    train_p.add_argument("--save-path", "-s", type=str, required=True, help="Path to save weights")
    train_p.add_argument("--model", type=str, default="distilgpt2", help="Base model name")

    return parser


def run_compare(args: argparse.Namespace) -> None:
    """Execute side-by-side comparison between N-gram and LoRA-adapted LLM."""
    print(f"\n[1/3] Loading sports commentary corpus from: {args.corpus or 'bundled corpus'}...")
    corpus = load_corpus(args.corpus)
    print(f"      Corpus loaded ({len(corpus.split())} words).")

    # 1. Train and generate N-gram model
    print(f"\n[2/3] Training {args.ngram_order}-gram model from scratch...")
    ngram_model = NGramModel(n=args.ngram_order)
    ngram_model.train(corpus)
    ngram_text = ngram_model.generate(prompt=args.prompt, max_tokens=args.max_tokens)
    ngram_stats = {"order": args.ngram_order, "vocab_size": len(ngram_model.vocab)}
    print(f"      N-gram generation complete (Vocabulary size: {ngram_stats['vocab_size']}).")

    # 2. Setup LoRA Model
    print(f"\n[3/3] Preparing LoRA-adapted LLM (Base: {args.model}, Rank: {args.rank})...")
    model, tokenizer = load_model_and_tokenizer(model_name=args.model)
    inject_lora_adapters(model, target_modules=("c_attn",), rank=args.rank, alpha=args.alpha)
    param_stats = get_trainable_parameters(model)
    print(f"      LoRA Injected. Trainable parameters: {param_stats['trainable']:,} / {param_stats['total']:,} ({param_stats['percent_trainable']}%)")

    if args.load_lora and Path(args.load_lora).exists():
        print(f"      Loading cached LoRA weights from {args.load_lora}...")
        load_lora_weights(model, args.load_lora)
    else:
        print(f"      Fine-tuning LoRA adapter for {args.epochs} epoch(s)...")
        losses = train_lora(model, tokenizer, corpus_text=corpus, epochs=args.epochs)
        print(f"      Training complete. Losses per epoch: {losses}")
        if args.save_lora:
            save_lora_weights(model, args.save_lora)
            print(f"      LoRA weights saved to {args.save_lora}")

    print("      Generating commentary with LoRA LLM...")
    lora_text = generate_llm(model, tokenizer, prompt=args.prompt, max_tokens=args.max_tokens)

    # 3. Print Side-by-Side Comparison
    lora_stats = {"rank": args.rank, "percent_trainable": f"{param_stats['percent_trainable']}%"}
    table = format_side_by_side(
        prompt=args.prompt,
        ngram_text=ngram_text,
        lora_text=lora_text,
        ngram_stats=ngram_stats,
        lora_stats=lora_stats,
    )
    print("\n" + table + "\n")


def main(argv: list[str] | None = None) -> None:
    """Main CLI entry point."""
    parser = build_parser()

    # If invoked with no arguments, display help
    if argv is None and len(sys.argv) == 1:
        parser.print_help()
        return

    args = parser.parse_args(argv)

    if args.command == "hello":
        print("Stylistic Text Generator Comparator is ready. Open README.md for your milestones.")
    elif args.command == "compare":
        run_compare(args)
    elif args.command == "train-lora":
        corpus = load_corpus(args.corpus)
        model, tokenizer = load_model_and_tokenizer(model_name=args.model)
        inject_lora_adapters(model, rank=args.rank)
        train_lora(model, tokenizer, corpus_text=corpus, epochs=args.epochs)
        save_lora_weights(model, args.save_path)
        print(f"LoRA adapter weights successfully saved to {args.save_path}")
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
